"""Rebuild the browser catalog from an already downloaded RW3 compendium JSON."""
import json
import sys
from pathlib import Path

source = json.loads(Path(sys.argv[1]).read_text())
destination = Path(__file__).resolve().parents[1] / "src" / "data" / "rw3-catalog.js"


def select(record, fields):
    return {key: record[key] for key in fields.split() if key in record}


def encode(record):
    return json.dumps(record, ensure_ascii=False, separators=(",", ":"))


def table(name, records):
    return f"export const {name} = [\n" + "".join(f"  {encode(row)},\n" for row in records) + "];\n"


spells = []
for spell in source["spells"]:
    row = select(spell, "id name level tags damage_type stats requires_los melee quick_cast desc upgrades summons pool_summons granted_by")
    # Forbidden spells only have a spell-point purchase ID in the source.
    row.setdefault("id", 10000 + spell["sp_id"])
    spells.append(row)

units = []
for unit in source["units"].values():
    row = select(unit, "name hp shields tags resists abilities passives difficulty rare boss_kind escorted_by pools")
    for flag in ("flying", "stationary", "burrowing", "radius", "is_boss", "is_monster", "is_companion"):
        if unit[flag]:
            row[flag] = unit[flag]
    units.append(row)

meta = dict(name="RW3 Community Compendium", generated=source["generated"],
            buildId=source["build_id"], branch=source["branch"])
destination.write_text("// Generated by scripts/import-compendium.py from https://hpp3.github.io/rw3/\n"
    + table("rw3Spells", spells)
    + table("rw3Equipment", (select(x, "id name slot tags recipe recipe_cost desc bonuses attributes effects mod_stats use_stats summons") for x in source["equipment"]))
    + table("rw3Components", (select(x, "name tags tier rare pool on_craft on_pickup desc effects summons") for x in source["components"]))
    + table("rw3Units", units)
    + table("wardrobe", (select(x, "name unlock") for x in source["costumes"]))
    + "export const spawnBands = " + encode(source["spawn_bands"]) + ";\n"
    + "export const rw3Catalogue = { source: " + encode(meta) + ", spells: rw3Spells, equipment: rw3Equipment, components: rw3Components };\n"
    + "export const rw3Tags = [...new Set([...rw3Spells, ...rw3Equipment, ...rw3Components].flatMap(item => item.tags))].sort();\n")
